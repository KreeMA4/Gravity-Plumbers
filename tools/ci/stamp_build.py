#!/usr/bin/env python3
"""Stamp this CI run into the build (used by .github/workflows/android-apk.yml).

  python3 tools/ci/stamp_build.py RUN_NUMBER COMMIT_SHA

- Rewrites scripts/core/build_info.gd so the game shows "CI run N (abc1234)".
- Sets the Android preset's versionName to "<project version>-runN" and its
  versionCode to N. Run numbers only grow, so each new APK installs over the last.
- Prints KEY=VALUE lines (version_name, version_code, label) for $GITHUB_OUTPUT.
The edits happen only in the CI checkout; they are never committed.
"""
import re
import sys

run = int(sys.argv[1])
commit = sys.argv[2][:7]
if run <= 10:
    sys.exit("run number %d must be > 10 (the committed versionCode) so the APK upgrades cleanly" % run)

proj = open("project.godot", encoding="utf-8").read()
m = re.search(r'^config/version="([^"]+)"', proj, re.M)
if not m:
    sys.exit("project.godot has no application/config/version")
version_name = "%s-run%d" % (m.group(1), run)
label = "CI run %d (%s)" % (run, commit)

with open("scripts/core/build_info.gd", "w", encoding="utf-8") as f:
    f.write(
        "class_name BuildInfo\nextends RefCounted\n"
        "## Generated by tools/ci/stamp_build.py for GitHub Actions run %d. Not committed.\n\n"
        "const RUN_NUMBER: int = %d\nconst COMMIT: String = \"%s\"\nconst LABEL: String = \"%s\"\n"
        % (run, run, commit, label))

presets = open("export_presets.cfg", encoding="utf-8").read()
presets, n1 = re.subn(r'^version/code=\d+$', "version/code=%d" % run, presets, flags=re.M)
presets, n2 = re.subn(r'^version/name="[^"]*"$', 'version/name="%s"' % version_name, presets, flags=re.M)
if n1 != 1 or n2 != 1:
    sys.exit("expected exactly one version/code and version/name in export_presets.cfg (got %d, %d)" % (n1, n2))
open("export_presets.cfg", "w", encoding="utf-8").write(presets)

print("version_name=%s" % version_name)
print("version_code=%d" % run)
print("label=%s" % label)
